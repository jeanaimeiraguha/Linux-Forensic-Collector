"""Configuration loading and validation for LFC.

Design rules:
  * Defaults live in code so the tool runs without a config file.
  * User config (JSON) overrides defaults, one layer deep per section.
  * SMTP credentials are NEVER stored in config — only the *names* of the
    environment variables that hold them (username_env / password_env).
  * All user-supplied values are validated before use.
"""

from __future__ import annotations

import copy
import json
import os
import re
from pathlib import Path
from typing import Any

DEFAULTS: dict[str, Any] = {
    "meta": {
        "org_name": "Not specified",
        "report_classification": "CONFIDENTIAL",
        "report_contact": "",
        "template_version": 1,
    },
    "collection": {
        "scope_paths": ["$HOME"],
        "include_hidden_paths": False,
        "cross_filesystems": False,
        "max_depth": 10,
        "max_files": 100000,
        "large_file_threshold_mb": 500,
        "json_max_inventory_rows": 5000,
        "modules": {
            "system": True,
            "filesystem": True,
            "media": True,
            "browser": True,
            "network": True,
            "software": True,
        },
    },
    "smtp": {
        "enabled": False,
        "host": "",
        "port": 587,
        "tls_mode": "starttls",
        "timeout_seconds": 30,
        "username_env": "LFC_SMTP_USERNAME",
        "password_env": "LFC_SMTP_PASSWORD",
        "from_addr": "",
        "to_addr": [],
        "max_attachment_mb": 20,
        "attach_format": "zip",
        "subject_prefix": "[LFC]",
    },
    "report": {
        "include_full_inventory_in_json": False,
        "company_footer": (
            "Generated by Linux Forensic Collector (LFC). Handle according to "
            "your organization's data classification policy."
        ),
    },
}

EMAIL_RE = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]{2,}$")
TLS_MODES = ("starttls", "ssl", "none")
ATTACH_FORMATS = ("zip", "files")
MODULE_NAMES = ("system", "filesystem", "media", "browser", "network", "software")


class ConfigError(Exception):
    """Raised when configuration fails validation."""


def _deep_merge(base: dict, override: dict) -> dict:
    out = copy.deepcopy(base)
    for key, value in override.items():
        if key in out and isinstance(out[key], dict) and isinstance(value, dict):
            out[key] = _deep_merge(out[key], value)
        else:
            out[key] = copy.deepcopy(value)
    return out


def _expand(value: Any) -> Any:
    """Expand $HOME-style variables in strings and string lists."""
    if isinstance(value, str):
        return os.path.expandvars(os.path.expanduser(value))
    if isinstance(value, list):
        return [_expand(v) for v in value]
    return value


def load_config(path: str | os.PathLike | None = None) -> dict[str, Any]:
    """Load config from *path* (or defaults when path is None/missing)."""
    cfg = copy.deepcopy(DEFAULTS)
    if path:
        p = Path(path)
        if not p.is_file():
            raise ConfigError(f"config file not found: {p}")
        try:
            raw = json.loads(p.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            raise ConfigError(f"invalid JSON in {p}: {exc}") from exc
        if not isinstance(raw, dict):
            raise ConfigError(f"config root must be a JSON object: {p}")
        cfg = _deep_merge(cfg, raw)

    # Expand environment variables in path-like fields.
    cfg["collection"]["scope_paths"] = _expand(cfg["collection"].get("scope_paths", []))
    return cfg


def validate(cfg: dict[str, Any]) -> list[str]:
    """Return a list of validation errors (empty list == valid)."""
    errors: list[str] = []

    def _int_in(section: str, key: str, lo: int, hi: int) -> None:
        value = cfg.get(section, {}).get(key)
        if not isinstance(value, int) or isinstance(value, bool):
            errors.append(f"{section}.{key} must be an integer (got {value!r})")
        elif not (lo <= value <= hi):
            errors.append(f"{section}.{key} must be between {lo} and {hi} (got {value})")

    meta = cfg.get("meta")
    if not isinstance(meta, dict):
        errors.append("meta must be an object")

    coll = cfg.get("collection")
    if not isinstance(coll, dict):
        errors.append("collection must be an object")
        coll = {}
    else:
        scope = coll.get("scope_paths")
        if not isinstance(scope, list) or not all(isinstance(s, str) for s in scope):
            errors.append("collection.scope_paths must be a list of strings")
        elif any(not s.strip() for s in scope):
            errors.append("collection.scope_paths must not contain empty entries")
        _int_in("collection", "max_depth", 1, 64)
        _int_in("collection", "max_files", 1, 5_000_000)
        _int_in("collection", "large_file_threshold_mb", 1, 1_000_000)
        _int_in("collection", "json_max_inventory_rows", 0, 1_000_000)
        modules = coll.get("modules")
        if not isinstance(modules, dict):
            errors.append("collection.modules must be an object")
        else:
            unknown = set(modules) - set(MODULE_NAMES)
            if unknown:
                errors.append(
                    "collection.modules contains unknown module(s): "
                    + ", ".join(sorted(unknown))
                )
            for name, val in modules.items():
                if not isinstance(val, bool):
                    errors.append(f"collection.modules.{name} must be true/false")

    smtp = cfg.get("smtp")
    if not isinstance(smtp, dict):
        errors.append("smtp must be an object")
        smtp = {}
    else:
        if not isinstance(smtp.get("enabled"), bool):
            errors.append("smtp.enabled must be true/false")
        port = smtp.get("port")
        if not isinstance(port, int) or isinstance(port, bool) or not (1 <= port <= 65535):
            errors.append(f"smtp.port must be an integer in 1..65535 (got {port!r})")
        if smtp.get("tls_mode") not in TLS_MODES:
            errors.append(f"smtp.tls_mode must be one of {TLS_MODES}")
        if smtp.get("attach_format") not in ATTACH_FORMATS:
            errors.append(f"smtp.attach_format must be one of {ATTACH_FORMATS}")
        timeout = smtp.get("timeout_seconds")
        if not isinstance(timeout, int) or isinstance(timeout, bool) or not (1 <= timeout <= 600):
            errors.append("smtp.timeout_seconds must be an integer in 1..600")
        max_mb = smtp.get("max_attachment_mb")
        if not isinstance(max_mb, int) or isinstance(max_mb, bool) or max_mb < 1:
            errors.append("smtp.max_attachment_mb must be a positive integer")

        to_addr = smtp.get("to_addr")
        if not isinstance(to_addr, list) or not all(isinstance(a, str) for a in to_addr):
            errors.append("smtp.to_addr must be a list of email addresses")
        else:
            for addr in to_addr:
                if not EMAIL_RE.match(addr):
                    errors.append(f"smtp.to_addr contains invalid address: {addr!r}")

        from_addr = smtp.get("from_addr")
        if not isinstance(from_addr, str) or (from_addr and not EMAIL_RE.match(from_addr)):
            errors.append(f"smtp.from_addr is not a valid email address: {from_addr!r}")

        for key in ("username_env", "password_env"):
            val = smtp.get(key)
            if not isinstance(val, str) or not re.match(r"^[A-Z_][A-Z0-9_]*$", val or ""):
                errors.append(f"smtp.{key} must be an environment variable name (A-Z, 0-9, _)")

        if smtp.get("enabled"):
            if not str(smtp.get("host", "")).strip():
                errors.append("smtp.host is required when smtp.enabled is true")
            if not to_addr:
                errors.append("smtp.to_addr is required when smtp.enabled is true")
            if not from_addr:
                errors.append("smtp.from_addr is required when smtp.enabled is true")

    report = cfg.get("report")
    if not isinstance(report, dict):
        errors.append("report must be an object")

    return errors


def require_valid(cfg: dict[str, Any]) -> None:
    errors = validate(cfg)
    if errors:
        raise ConfigError("configuration invalid:\n  - " + "\n  - ".join(errors))


def get_dotted(cfg: dict[str, Any], dotted: str) -> Any:
    node: Any = cfg
    for part in dotted.split("."):
        if not isinstance(node, dict) or part not in node:
            raise KeyError(dotted)
        node = node[part]
    return node


def _stringify(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return ",".join(str(v) for v in value)
    if value is None:
        return ""
    return str(value)


def config_cli(argv: list[str]) -> int:
    """CLI used by the Bash engine: `python -m collector config ...`."""
    import argparse

    parser = argparse.ArgumentParser(prog="lfc config", description="Read validated LFC config values")
    parser.add_argument("--config", default=None, help="path to JSON config file")
    parser.add_argument("--get", metavar="KEY", help="print a dotted config value")
    parser.add_argument("--get-array", metavar="KEY", help="print a list value, one entry per line")
    parser.add_argument("--flatten", action="store_true", help="print every key as KEY<TAB>VALUE")
    parser.add_argument("--validate", action="store_true", help="validate and exit non-zero on error")
    parser.add_argument("--print", dest="print_all", action="store_true", help="print the effective config")
    args = parser.parse_args(argv)

    try:
        cfg = load_config(args.config)
        require_valid(cfg)
    except ConfigError as exc:
        print(str(exc), file=__import__("sys").stderr)
        return 3

    if args.validate:
        print("configuration OK")
        return 0
    if args.get:
        try:
            print(_stringify(get_dotted(cfg, args.get)))
        except KeyError:
            print(f"unknown config key: {args.get}", file=__import__("sys").stderr)
            return 3
        return 0
    if args.get_array:
        try:
            value = get_dotted(cfg, args.get_array)
        except KeyError:
            print(f"unknown config key: {args.get_array}", file=__import__("sys").stderr)
            return 3
        if not isinstance(value, list):
            print(f"config key is not a list: {args.get_array}", file=__import__("sys").stderr)
            return 3
        for item in value:
            print(item)
        return 0
    if args.flatten:
        def _walk(node: dict, prefix: str) -> None:
            for key, val in node.items():
                dotted = f"{prefix}.{key}" if prefix else key
                if isinstance(val, dict):
                    _walk(val, dotted)
                else:
                    print(f"{dotted}\t{_stringify(val)}")
        _walk(cfg, "")
        return 0
    if args.print_all:
        print(json.dumps(cfg, indent=2, sort_keys=True))
        return 0

    parser.print_help()
    return 0
